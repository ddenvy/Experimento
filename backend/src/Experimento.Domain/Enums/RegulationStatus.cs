namespace Experimento.Domain.Enums;

/// <summary>
/// Степень ограничения вещества по конкретному регулятору.
/// Порядок важен: от менее к более строгому.
/// </summary>
public enum RegulationStatus
{
    /// <summary>Вещество не указано в данном регуляторном списке — проверка не выявила рисков.</summary>
    Compliant = 0,

    /// <summary>Ограничено — требует разрешения, мониторинга или имеет пределы концентрации.</summary>
    Restricted = 1,

    /// <summary>Запрещено / в списке веществ высокой степени опасности.</summary>
    Banned = 2,
}
